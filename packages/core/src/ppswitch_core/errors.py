"""Typed API errors with stable machine-readable codes.

Error codes and HTTP statuses follow docs/07-API-SPEC.md section 10.
Every message returned to a caller must be a safe constant: never echo
upstream bodies, internal stack traces or secret material.
"""

from enum import StrEnum

HTTP_BAD_REQUEST = 400
HTTP_UNAUTHORIZED = 401
HTTP_FORBIDDEN = 403
HTTP_NOT_FOUND = 404
HTTP_CONFLICT = 409
HTTP_GONE = 410
HTTP_PAYLOAD_TOO_LARGE = 413
HTTP_UNPROCESSABLE = 422
HTTP_TOO_MANY_REQUESTS = 429
HTTP_BAD_GATEWAY = 502
HTTP_SERVICE_UNAVAILABLE = 503
HTTP_GATEWAY_TIMEOUT = 504


class ErrorCode(StrEnum):
    BAD_REQUEST = "BAD_REQUEST"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    FORBIDDEN = "FORBIDDEN"
    NOT_FOUND = "NOT_FOUND"
    WORKSPACE_NOT_FOUND = "WORKSPACE_NOT_FOUND"
    SERVICE_NOT_FOUND = "SERVICE_NOT_FOUND"
    OPERATION_NOT_FOUND = "OPERATION_NOT_FOUND"
    CAPABILITY_NOT_FOUND = "CAPABILITY_NOT_FOUND"
    PROFILE_NOT_FOUND = "PROFILE_NOT_FOUND"
    CONNECTION_NOT_FOUND = "CONNECTION_NOT_FOUND"
    ENDPOINT_NOT_FOUND = "ENDPOINT_NOT_FOUND"
    PROFILE_NOT_ALLOWED = "PROFILE_NOT_ALLOWED"
    PROFILE_VERSION_CONFLICT = "PROFILE_VERSION_CONFLICT"
    APPROVAL_REQUIRED = "APPROVAL_REQUIRED"
    SCHEMA_VIOLATION = "SCHEMA_VIOLATION"
    RESERVED_ARGUMENT = "RESERVED_ARGUMENT"
    UNSANITIZED_INPUT = "UNSANITIZED_INPUT"
    NO_ACTIVE_PROFILE = "NO_ACTIVE_PROFILE"
    QUOTA_EXCEEDED = "QUOTA_EXCEEDED"
    UPSTREAM_FAILURE = "UPSTREAM_FAILURE"
    SECRET_PROVIDER_UNAVAILABLE = "SECRET_PROVIDER_UNAVAILABLE"  # noqa: S105 - error code
    UPSTREAM_TIMEOUT = "UPSTREAM_TIMEOUT"
    INVALID_SIGNATURE = "INVALID_SIGNATURE"
    DEADLINE_EXCEEDED = "DEADLINE_EXCEEDED"
    REPLAY_DETECTED = "REPLAY_DETECTED"
    PAYLOAD_TOO_LARGE = "PAYLOAD_TOO_LARGE"
    CONFLICT = "CONFLICT"
    CAPABILITY_NOT_REVIEWED = "CAPABILITY_NOT_REVIEWED"
    CAPABILITY_NOT_VERIFIED = "CAPABILITY_NOT_VERIFIED"
    IMMUTABLE_VERSION = "IMMUTABLE_VERSION"
    IDEMPOTENCY_KEY_CONFLICT = "IDEMPOTENCY_KEY_CONFLICT"
    ENDPOINT_NOT_APPROVABLE = "ENDPOINT_NOT_APPROVABLE"


_STATUS_BY_CODE: dict[ErrorCode, int] = {
    ErrorCode.BAD_REQUEST: HTTP_BAD_REQUEST,
    ErrorCode.UNAUTHENTICATED: HTTP_UNAUTHORIZED,
    ErrorCode.FORBIDDEN: HTTP_FORBIDDEN,
    ErrorCode.NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.WORKSPACE_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.SERVICE_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.OPERATION_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.CAPABILITY_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.PROFILE_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.CONNECTION_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.ENDPOINT_NOT_FOUND: HTTP_NOT_FOUND,
    ErrorCode.PROFILE_NOT_ALLOWED: HTTP_FORBIDDEN,
    ErrorCode.PROFILE_VERSION_CONFLICT: HTTP_CONFLICT,
    ErrorCode.APPROVAL_REQUIRED: HTTP_CONFLICT,
    ErrorCode.SCHEMA_VIOLATION: HTTP_UNPROCESSABLE,
    ErrorCode.RESERVED_ARGUMENT: HTTP_UNPROCESSABLE,
    ErrorCode.UNSANITIZED_INPUT: HTTP_UNPROCESSABLE,
    ErrorCode.NO_ACTIVE_PROFILE: HTTP_CONFLICT,
    ErrorCode.QUOTA_EXCEEDED: HTTP_TOO_MANY_REQUESTS,
    ErrorCode.UPSTREAM_FAILURE: HTTP_BAD_GATEWAY,
    ErrorCode.SECRET_PROVIDER_UNAVAILABLE: HTTP_SERVICE_UNAVAILABLE,
    ErrorCode.UPSTREAM_TIMEOUT: HTTP_GATEWAY_TIMEOUT,
    ErrorCode.INVALID_SIGNATURE: HTTP_UNAUTHORIZED,
    ErrorCode.DEADLINE_EXCEEDED: HTTP_GONE,
    ErrorCode.REPLAY_DETECTED: HTTP_CONFLICT,
    ErrorCode.PAYLOAD_TOO_LARGE: HTTP_PAYLOAD_TOO_LARGE,
    ErrorCode.CONFLICT: HTTP_CONFLICT,
    ErrorCode.CAPABILITY_NOT_REVIEWED: HTTP_CONFLICT,
    ErrorCode.CAPABILITY_NOT_VERIFIED: HTTP_CONFLICT,
    ErrorCode.IMMUTABLE_VERSION: HTTP_CONFLICT,
    ErrorCode.IDEMPOTENCY_KEY_CONFLICT: HTTP_CONFLICT,
    ErrorCode.ENDPOINT_NOT_APPROVABLE: HTTP_FORBIDDEN,
}


class ApiError(Exception):
    """Domain error that maps to a stable JSON error envelope."""

    def __init__(self, code: ErrorCode, message: str, details: dict | None = None) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details or {}
        self.http_status = _STATUS_BY_CODE[code]

    def __repr__(self) -> str:  # pragma: no cover - debug helper
        return f"ApiError({self.code}, {self.message!r})"
